def report_generation_node(state:AgentState):
    file_path = state.get("cleaned_file_path") or state["file_path"]
    df = load_dataframe(file_path)

    overview = build_dataset_overview(df)
    cleaning_summary = build_cleaning_summary(state['cleaning_issues'],state['cleaning_decisions'])
    anomalies = build_annomalies_detection(state['cleaning_issues'],state['cleaning_decisions'])
    key_findings = generate_key_findings(state['eda_results'])
    plain_summary = generate_plain_summary(key_findings)

    report_sections = {
            "overview": overview,
            "cleaning_summary": cleaning_summary,
            "anomalies": anomalies,
            "key_findings": key_findings,
            "plain_summary": plain_summary,
            "chart_paths": state["eda_results"]["chart_paths"]
        }

    output_path = os.path.splitext(file_path)[0] + "_report.docx"
    assemble_report(report_sections,output_path)

    return {
        "report_file_path": output_path,
        "report_sections":  report_sections,
        "report_generated": True
    }



